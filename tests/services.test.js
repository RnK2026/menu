test('shared meal code, independent config, no VoC in Daerim output',()=>{
  assert.equal(read('_site/daerim/app.js'),read('_site/rnk/app.js'));
  assert.equal(read('_site/daerim/core.js'),read('_site/rnk/core.js'));
  assert.doesNotMatch(read('_site/daerim/index.html'),/VoC|voc-section|admin-voc|data-tab=".*voc/);
  assert.match(read('_site/rnk/index.html'),/id="menu-voc"/);
  assert.match(read('_site/rnk/index.html'),/id="vehicle-voc"/);
  assert.doesNotMatch(read('_site/daerim/index.html'),/vehicle-voc|차량 VoC/);
  assert.match(read('_site/daerim/index.html'),/대림/);
  assert.equal(existsSync('_site/daerim/voc-app.js'),false);
  const daerimURL=JSON.parse(read('_site/daerim/config.json')).apiUrl;
  assert.equal(daerimURL,JSON.parse(read('services/daerim/config.json')).apiUrl);
  if(daerimURL)assert.notEqual(daerimURL,JSON.parse(read('config.json')).apiUrl);
  assert.notEqual(rnk.service.id,daerim.service.id);
  assert.equal(daerim.service.voc,false);
});
test('Daerim defaults apply to blanks and preserve special breakfast',()=>{
  assert.equal(daerim.menuValue(undefined,'breakfast'),'-');
  assert.equal(daerim.menuValue('  ','breakfast'),'-');
  assert.equal(daerim.menuValue('특별 조식','breakfast'),'특별 조식');
  assert.equal(rnk.menuValue('','breakfast'),'');
  const sample={...base,days:[{date:'2026-09-16',breakfast:'',lunch:'점심',dinner:'저녁'}]};
  const defaults=daerim.applyDefaults(sample);
  assert.equal(sample.days[0].breakfast,'');
  assert.equal(defaults.days[0].breakfast,'-');
  assert.equal(upcoming(defaults,new Date('2026-09-16T03:00:00Z'),true)[0].key,'lunch');
  defaults.days[0].breakfast='특별 조식';
  assert.equal(upcoming(defaults,new Date('2026-09-16T03:00:00Z'),true)[0].key,'breakfast');
});
