import {readFileSync as read,writeFileSync as write,mkdirSync as mkdir,copyFileSync as copy} from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const get=p=>read(p,'utf8');
export function build(target='rnk',out=`_site/${target}`){
  if(!['rnk','daerim'].includes(target))throw Error('Unknown service');
  mkdir(out,{recursive:true});mkdir(path.join(out,'data'),{recursive:true});
  let html=get('index.html');
  if(target==='daerim')html=html.replace(/<!-- VOC-START -->[\s\S]*?<!-- VOC-END -->/,'').replace(/<!-- ADMIN-VOC-START -->[\s\S]*?<!-- ADMIN-VOC-END -->/,'').replace(/<button data-tab="(?:menu-voc|lodging-voc|vehicle-voc)">[^<]*<\/button>/g,'').replaceAll('RnK','대림').replace('RNK MEAL','DAERIM MEAL').replace('<span class="logo">R</span>','<span class="logo">D</span>').replace('주간 메뉴와 고객 의견을 관리하세요.','대림의 주간 메뉴를 관리하세요.').replace('저장·삭제할 때 사용','식단을 저장할 때 사용');
  write(path.join(out,'index.html'),html);
  write(path.join(out,'source-revision.txt'),execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim());
  for(const file of ['app.js','core.js','style.css','i18n.js','messages.js','translated-content.js','poll-app.js'])copy(file,path.join(out,file));
  if(target==='rnk')for(const file of ['voc.js','voc-app.js'])copy(file,path.join(out,file));
  write(path.join(out,'service.js'),target==='rnk'?get('service.js'):get('service.js').replace("id:'rnk',name:'RnK',voc:true,breakfastDefault:''","id:'daerim',name:'대림',voc:false,breakfastDefault:'-'"));
  copy(target==='rnk'?'service-extension.js':'services/daerim/extension.js',path.join(out,'service-extension.js'));
  copy(target==='rnk'?'config.json':'services/daerim/config.json',path.join(out,'config.json'));
  copy(target==='rnk'?'data/menu.json':'services/daerim/menu.json',path.join(out,'data/menu.json'));
}
export function buildBackends(){
  const common=get('apps-script/shared/Meal.gs')+get('apps-script/shared/Translation.gs')+get('apps-script/shared/Poll.gs');
  write('apps-script/Code.gs', '// Generated by npm run build. Edit shared/ and templates/.\n'+common+get('apps-script/templates/rnk.gs'));
  write('apps-script/Daerim.gs','// Generated by npm run build. Use in a NEW Apps Script project.\n'+common+get('apps-script/templates/daerim.gs'));
}
if(process.argv[1]&&path.resolve(process.argv[1])===path.resolve('scripts/build.mjs')){
  buildBackends();
  if(process.argv[2])build(process.argv[2]);else {build('rnk');build('daerim');}
}
